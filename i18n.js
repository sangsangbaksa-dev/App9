// Language choice: a saved choice first, then the first supported browser language, then Korean.
export function detectLang(saved, nav = (typeof navigator !== 'undefined' ? navigator.languages || [navigator.language] : [])) {
  if (saved && LANGS[saved]) return saved;
  for (const l of nav || []) {
    const c = String(l || '').slice(0, 2).toLowerCase();
    if (LANGS[c]) return c;
  }
  return DEFAULT_LANG;
}
// localStorage can throw (private mode, blocked storage); the app then falls back to the browser language.
export function readSavedLang() {
  try { return localStorage.getItem(LANG_KEY); } catch { return null; }
}
export function saveLang(code) {
  try { localStorage.setItem(LANG_KEY, code); return true; } catch { return false; }
}

let lang = DEFAULT_LANG;
export const getLang = () => lang;
export const setLang = (code) => { lang = LANGS[code] ? code : DEFAULT_LANG; };
export const locale = () => LANGS[lang].locale;

export function t(key, vars = {}) {
  const table = DICT[lang] || DICT[DEFAULT_LANG];
  const s = table[key] ?? DICT[DEFAULT_LANG][key] ?? DICT.en[key];
  if (s === undefined) return `missing:${key}`;
  return s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m));
}

// Number, date and name formatting in the selected locale. Plain text if Intl is unavailable.
export function fmtNumber(n, opts = {}) {
  try { return new Intl.NumberFormat(locale(), opts).format(n); } catch { return String(n); }
}
// ISO date (YYYY-MM-DD) shown in the selected locale. Other input is returned unchanged.
export function fmtDate(iso) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(iso ?? ''))) return String(iso ?? '');
  try {
    return new Intl.DateTimeFormat(locale(), { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'UTC' })
      .format(new Date(iso + 'T00:00:00Z'));
  } catch { return iso; }
}
/** Short month name for month 1-12, e.g. "1월", "Jan". */
export function monthShort(m) {
  try { return new Intl.DateTimeFormat(locale(), { month: 'short', timeZone: 'UTC' }).format(new Date(Date.UTC(2024, m - 1, 1))); }
  catch { return String(m); }
}
/** Year and month name, e.g. "2026년 11월", "November 2026". */
export function monthName(y, m) {
  try { return new Intl.DateTimeFormat(locale(), { year: 'numeric', month: 'long', timeZone: 'UTC' }).format(new Date(Date.UTC(y, m - 1, 1))); }
  catch { return `${y}-${m}`; }
}
/** Short weekday name for index 0 (Sunday) to 6 (Saturday). */
export function weekdayShort(i) {
  try { return new Intl.DateTimeFormat(locale(), { weekday: 'short', timeZone: 'UTC' }).format(new Date(Date.UTC(2024, 0, 7 + i))); }
  catch { return String(i); }
}

// Fills static markup: data-i18n (text), data-i18n-attr="attr=key;attr2=key2" (attributes).
// Text is set with textContent, never innerHTML.
export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((e) => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll('[data-i18n-attr]').forEach((e) => {
    for (const pair of e.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split('=').map((s) => s.trim());
      if (attr && key) e.setAttribute(attr, t(key));
    }
  });
}
